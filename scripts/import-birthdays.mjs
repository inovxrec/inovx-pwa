#!/usr/bin/env node
/*
  Turns the member-cards site's roster into a birthday migration.

  Where the dates come from
  -------------------------
  https://adizzsk23.github.io/inovx-member-cards/ publishes `data/members.json`,
  which is generated from the club's own Google Sheet. That file is the only
  place the club has ever written its birthdays down, so it is the source here
  rather than a second list typed into this repo — a birthday corrected on the
  sheet should be correctable here by re-running this, not by hand-editing SQL.

  Matched on email, never on name
  -------------------------------
  The two rosters disagree about names in six places — "Mayank Sharm" against
  "Mayank Sharma", "K.S. Sree Vishal" against "Sree Vishal K S", "PavanPrasad P"
  against "Pavan Prasad P" — because one was typed by the people themselves and
  the other by whoever built the seed. The addresses are identical in all thirty
  cases, and an address is issued by the college rather than typed, so it is the
  only key here that cannot drift.

  Anyone the cards site has no date for is simply absent from the output. They
  keep a NULL birthday and generate no occasion, which is the honest outcome —
  a guessed date would put a stranger's name on a poster.

  Usage:

    node scripts/import-birthdays.mjs            # writes the migration
    node scripts/import-birthdays.mjs --stdout   # prints it instead
*/

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE = 'https://adizzsk23.github.io/inovx-member-cards/data/members.json';
const TENURE = '11111111-1111-1111-1111-111111111111';
const DESIGN_DOMAIN = '22222222-2222-2222-2222-000000000005';

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'supabase',
  'migrations',
  '20260920000000_birthdays.sql',
);

/** Postgres string literal. Addresses are ASCII, but this is not the place to assume it. */
function quote(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

const response = await fetch(SOURCE);
if (!response.ok) {
  console.error(`Could not read ${SOURCE} — HTTP ${response.status}`);
  process.exit(1);
}

const { generated, members } = await response.json();

const dated = members
  .filter((member) => member.email && /^\d{4}-\d{2}-\d{2}$/.test(member.dob ?? ''))
  .map((member) => ({ email: member.email.trim().toLowerCase(), dob: member.dob, name: member.name }))
  .sort((a, b) => a.email.localeCompare(b.email));

if (dated.length === 0) {
  console.error('No usable birthdays in the source. Refusing to write an empty migration.');
  process.exit(1);
}

/*
  The comma goes before the comment, not after it. Joining on ',\n' would push
  each separator to the end of the line the name is on, which is inside a `--`
  comment — the list would parse as one row and the migration would silently
  update a single person.
*/
const rows = dated
  .map(
    (member, index) =>
      `  (${quote(member.email)}, DATE ${quote(member.dob)})` +
      `${index < dated.length - 1 ? ',' : ' '}  -- ${member.name}`,
  )
  .join('\n');

const sql = `-- ==============================================================================
-- INOVX OPS — THE BIRTHDAYS, AT LAST
-- Migration: 20260920000000_birthdays.sql
-- ==============================================================================
--
-- GENERATED by scripts/import-birthdays.mjs from
--   ${SOURCE}
-- (that file's own \`generated\` stamp: ${generated})
-- Re-run the script rather than editing this by hand.
--
-- The gap this closes
-- -------------------
-- \`member_directory.birthday\` has been NULL for everyone since the club was
-- seeded, and the seed said so out loud: "Birthdays are left NULL because
-- nobody has collected them." Three finished surfaces have been reading that
-- NULL ever since and showing nothing — \`upcomingBirthdays()\` behind §9.10's
-- BIRTHDAYS tab, the Calendar's occasions layer, and the occasion generator at
-- the end of seed_club_only.sql, which selects \`WHERE birthday IS NOT NULL\`
-- and has therefore always selected nothing.
--
-- Nothing here invents a date. ${dated.length} of the roster have one on the cards
-- site; the rest keep their NULL and generate no occasion, and the People screen
-- will keep saying so rather than filling the gap with a guess.

-- ------------------------------------------------------------------------------
-- 1. The dates
-- ------------------------------------------------------------------------------
-- Matched on email. The two rosters disagree about several spellings of the
-- same person's name and agree about every address.
WITH incoming (email, dob) AS (
  VALUES
${rows}
)
UPDATE member_directory md
SET birthday = incoming.dob
FROM incoming
WHERE LOWER(md.email) = incoming.email
  AND md.tenure_id = ${quote(TENURE)}
  AND md.birthday IS DISTINCT FROM incoming.dob;

-- ------------------------------------------------------------------------------
-- 2. Tie a generated task back to the occasion that asked for it
-- ------------------------------------------------------------------------------
-- Until now the Calendar worked out which tasks an occasion produced by
-- searching task titles for the person's first name (src/lib/club.ts). That is
-- a guess: it misses a poster titled "Sandhiya bday banner" and it claims one
-- titled "Harini to review the Harini poster" twice. The birthday reminders in
-- the next migration have to answer "has this actually been made" exactly, so
-- the link becomes a column.
ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS occasion_id UUID REFERENCES occasions(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_tasks_occasion ON tasks(occasion_id) WHERE occasion_id IS NOT NULL;

-- ------------------------------------------------------------------------------
-- 3. Raise the occasions the dates now make possible
-- ------------------------------------------------------------------------------
-- The same SELECT the seed has always carried, run now that it has rows to find.
-- Design owns the output because the club's posters are Design's work; lead_days
-- stays at the seed's 5 so the board shows the work coming before the reminders
-- start. \`uq_occasions_tenure_name\` makes the re-run harmless.
INSERT INTO occasions (
  tenure_id, name, occasion_type, occasion_date,
  output_domain_id, lead_days, assignment_strategy, directory_member_id
)
SELECT
  md.tenure_id,
  md.name || ' — birthday',
  'birthday',
  TO_CHAR(md.birthday, 'MM-DD'),
  ${quote(DESIGN_DOMAIN)},
  5,
  'domain-lead',
  md.id
FROM member_directory md
WHERE md.tenure_id = ${quote(TENURE)}
  AND md.birthday IS NOT NULL
ON CONFLICT (tenure_id, name) DO NOTHING;

-- A birthday corrected above should correct the occasion with it, rather than
-- leaving the poster scheduled against last week's date.
UPDATE occasions o
SET occasion_date = TO_CHAR(md.birthday, 'MM-DD')
FROM member_directory md
WHERE o.directory_member_id = md.id
  AND o.occasion_type = 'birthday'
  AND md.birthday IS NOT NULL
  AND o.occasion_date IS DISTINCT FROM TO_CHAR(md.birthday, 'MM-DD');
`;

if (process.argv.includes('--stdout')) {
  process.stdout.write(sql);
} else {
  writeFileSync(OUT, sql);
  console.log(`Wrote ${OUT}`);
  console.log(`${dated.length} birthdays from a roster of ${members.length}.`);
}
